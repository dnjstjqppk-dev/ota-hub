#!/usr/bin/env node
/**
 * Generates database/seed_transfers.sql from the frontend transfer catalog so the
 * server (D1) knows every transfer the site lists. Without it, transfer quotes 404.
 *
 *   node scripts/gen-transfer-seed.mjs
 *
 * INSERT OR IGNORE: re-running never overwrites rows an operator has edited.
 * Applying it to a remote database is a deliberate, separate step.
 */
import { writeFileSync } from "node:fs";
import { MASTER_TRANSFER_CATALOG } from "../frontend-user/data/transferCatalog.ts";

const q = (v) => (v === null || v === undefined ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const rows = MASTER_TRANSFER_CATALOG.map((t) =>
  `  (${[t.id, "unassigned_transfer", t.vehicle_name, t.airport_code, t.destination_zone, t.vehicle_class, t.max_passengers, t.max_luggage, t.price_krw, t.flight_tracking ? 1 : 0, t.image_url].map(q).join(", ")})`,
);
const sql = `-- Generated by scripts/gen-transfer-seed.mjs from frontend-user/data/transferCatalog.ts. Do not edit by hand.
INSERT OR IGNORE INTO transfers (id, partner_id, service_title, airport_code, destination_area, vehicle_class, max_passengers, max_luggage, price_krw, flight_tracking, image_url) VALUES
${rows.join(",\n")};
`;
writeFileSync("database/seed_transfers.sql", sql);
console.log(`database/seed_transfers.sql: ${rows.length} transfers`);

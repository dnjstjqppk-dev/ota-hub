-- Migration 0006: places (search & autocomplete reference data)
--
-- One table for every searchable location: countries, cities, airports (IATA),
-- railway stations, cruise ports, districts and landmarks. Autocomplete selects
-- a place by id and hands the caller a stable identifier (IATA code, ISO country
-- code, place id) instead of free text.
--
-- This is public reference data (official names and IATA / ISO codes), not
-- product data: no prices, counts or availability are stored here.
-- `popularity` is an editorial ordering weight only and is never displayed.

CREATE TABLE IF NOT EXISTS places (
    id TEXT PRIMARY KEY,
    place_type TEXT NOT NULL CHECK (place_type IN ('COUNTRY','CITY','REGION','AIRPORT','STATION','PORT','LANDMARK')),
    code TEXT,                      -- IATA airport / city code, ISO 3166-1 alpha-2 for countries
    country_code TEXT NOT NULL,     -- ISO 3166-1 alpha-2
    parent_id TEXT REFERENCES places(id),
    name_ko TEXT NOT NULL,
    name_en TEXT NOT NULL,
    aliases TEXT NOT NULL DEFAULT '', -- '|'-separated extra search terms (local script, former names, short forms)
    popularity INTEGER NOT NULL DEFAULT 0,
    is_active INTEGER NOT NULL DEFAULT 1,
    created_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now')),
    updated_at TEXT NOT NULL DEFAULT (strftime('%Y-%m-%dT%H:%M:%fZ','now'))
);
CREATE INDEX IF NOT EXISTS idx_places_type ON places(place_type, is_active);
CREATE INDEX IF NOT EXISTS idx_places_code ON places(code);
CREATE INDEX IF NOT EXISTS idx_places_parent ON places(parent_id);
CREATE INDEX IF NOT EXISTS idx_places_country ON places(country_code);

